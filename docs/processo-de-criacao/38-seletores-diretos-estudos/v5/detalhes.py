"""Camadas de acabamento V5: facetas costeiras e detalhes de cada marco."""
from PIL import Image, ImageChops, ImageDraw, ImageFilter

W,H=480,360


def poligono(pontos):
    m=Image.new('L',(W,H))
    ImageDraw.Draw(m).polygon(pontos,fill=255)
    return m


def tom(a,b,peso):
    ra,rb=bytes.fromhex(a[1:]),bytes.fromhex(b[1:])
    return '#'+''.join(f'{round(x+(y-x)*peso):02x}' for x,y in zip(ra,rb))


def colocar(im,mascara,pontos,cor):
    im.paste(cor,(0,0,W,H),ImageChops.multiply(mascara,poligono(pontos)))


def costa(im,frente,solo,livre,pal):
    # Cortes em diagonal ligam os estratos em vez de acrescentar riscos soltos.
    # O recorte usa a mesma fachada que V4, sem deslocar sua silhueta.
    pedra=pal['pedra']
    for i,q in enumerate(range(52,436,29)):
        cima=88+(i*13)%29
        luz=tom(pedra[3],pedra[5],.38)
        penumbra=tom(pedra[0],pedra[2],.47)
        largura=10+((i*23)%17)
        pol=((q,cima),(q+largura,cima+1),(q+largura-3,336),(q+6,338),
             (q+1,293),(q+3,237),(q,190))
        colocar(im,frente,pol,penumbra if i%3==1 else luz)
        # O rebordo superior acende a faixa quente e deixa o degrau inferior escuro.
        for y in (169+((i*19)%35),229+((i*17)%37),284+((i*23)%24)):
            fenda=((q-3,y),(q+largura-5,y-4),(q+largura+7,y-1),(q+largura+4,y+2),
                   (q+3,y+8),(q-3,y+7))
            colocar(im,frente,fenda,pedra[(i+2)%3+1])
            borda=((q+1,y-1),(q+largura-3,y-5),(q+largura+7,y-2),(q+largura+2,y),
                   (q+4,y+4),(q-1,y+3))
            colocar(im,frente,borda,tom(luz,pedra[4],.37))
    # Vegetação rasteira/pedra no topo não pode invadir as áreas de navegação.
    interior=ImageChops.subtract(solo,solo.filter(ImageFilter.MinFilter(13)))
    zona=ImageChops.multiply(interior,livre)
    sombra=tom(pal['areia'],pal['sombra'],.40)
    for x,y,w in ((83,130,19),(405,136,16),(96,245,20),(399,246,18),
                  (132,276,20),(346,278,16),(204,293,15),(275,295,19)):
        escarpa=((x-w,y+3),(x-w+5,y-4),(x-4,y-6),(x+5,y-3),
                 (x+w-3,y-2),(x+w,y+2),(x+8,y+5),(x-2,y+5),(x-7,y+7))
        colocar(im,zona,escarpa,sombra)


def orla(im,solo,livre,pal):
    baixo=Image.new('L',(W,H))
    baixo.paste(solo,(4,25))
    rasinho=ImageChops.subtract(baixo.filter(ImageFilter.MaxFilter(29)),baixo.filter(ImageFilter.MaxFilter(9)))
    area=ImageChops.multiply(rasinho,livre)
    espuma=tom(pal['agua'][3],pal['agua'][4],.28)
    d=ImageDraw.Draw(im)
    for x,y in ((56,229),(77,260),(102,282),(133,305),(187,322),(291,328),
                (345,308),(381,287),(408,266),(430,231)):
        # Ondulação em vários patamares, com mais linhas interrompidas no rosto do mar.
        for i in range(3):
            v=y+i*4
            u=x+(-3,2,7)[i]
            if not (0<=u<W-13 and 0<=v<H-2 and area.getpixel((u,v))):
                continue
            pontos=((u,v),(u+5,v),(u+6,v+1),(u+12,v+1),(u+11,v+2),
                    (u+5,v+2),(u+4,v+1),(u,v+1))
            colocar(im,area,pontos,espuma if i==0 else pal['agua'][3])



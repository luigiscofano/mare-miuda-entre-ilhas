"""Estruturas decorativas sobre blocos inteiros de água não navegável."""
from PIL import Image, ImageDraw

def poly(d, cor, pontos):
    d.polygon(pontos, fill=cor)

def fio(d, cor, pontos, n=1):
    d.line(pontos, fill=cor, width=n)

def duna(d):
    """Restinga de areia firme e capim com alturas variadas."""
    poly(d,'#266a76',[(5,52),(13,43),(29,40),(36,33),(55,32),(70,39),(80,49),(75,58),(61,65),(49,71),(29,68),(13,64)])
    poly(d,'#4a9795',[(8,53),(16,44),(29,42),(40,35),(56,33),(69,39),(76,47),(77,55),(64,62),(47,68),(30,65),(14,61)])
    poly(d,'#bc9465',[(11,52),(20,43),(34,40),(43,34),(55,34),(68,39),(75,47),(73,53),(63,59),(47,65),(31,63),(22,59),(15,60)])
    poly(d,'#dfbd80',[(12,51),(20,43),(34,40),(43,34),(55,34),(68,39),(72,44),(65,48),(59,48),(53,56),(40,59),(26,56),(17,57)])
    poly(d,'#f6d894',[(17,49),(22,43),(35,40),(43,34),(54,34),(63,37),(66,40),(55,41),(48,39),(39,46),(27,45)])
    fio(d,'#f7e1a2',[(15,52),(22,51),(28,53),(43,54),(49,51),(54,50)])
    fio(d,'#91c0a8',[(9,57),(15,60),(23,60),(29,63),(40,65),(45,66)])
    for x,y,t in [(26,46,0),(41,42,3),(49,48,1),(57,42,5),(67,48,2),(33,53,-2)]:
        poly(d,'#6d7856',[(x-4,y+1),(x,y-2),(x+6,y-2),(x+9,y+1),(x+3,y+4),(x-3,y+3)])
        for a,h,b in [(-2,8,5),(1,12,3),(3,7,-4)]:
            fio(d,'#3f7660',[(x+a,y),(x+a+b//2,y-3),(x+a+b,y-h-t)],2)
            fio(d,'#a1bb6d',[(x+a+b//2-1,y-4),(x+a+b-1,y-h-t+1)])
    for x,y in [(19,52),(29,56),(43,57),(66,51),(51,58)]:
        fio(d,'#b58c63',[(x,y),(x+3,y)])

def coral(d,x,y,escala,rosado=True):
    sombra,base,luz=('#68445e','#be7588','#f8b3a1') if rosado else ('#715063','#b48879','#f1c792')
    ramos=[[(0,7),(0,-3),(-4,-9),(-8,-13)],
           [(0,2),(7,-3),(9,-11)],[(1,7),(9,4),(13,-1)],
           [(-2,4),(-9,4),(-13,-2)],[(-3,-6),(-2,-14),(-5,-19)]]
    for ramo in ramos:
        pontos=[(x+round(a*escala),y+round(b*escala)) for a,b in ramo]
        fio(d,sombra,pontos,round(6*escala))
        fio(d,base,[(a-1,b-1) for a,b in pontos],round(4*escala))
        fio(d,luz,[(a-2,b-2) for a,b in pontos[1:]],max(1,round(2*escala)))

def recife(d):
    """Uma única plataforma coralínea com dois pontos altos, vista de cima."""
    poly(d,'#254b63',[(6,48),(12,36),(22,29),(39,31),(49,35),(62,31),(73,37),(79,47),(76,60),(66,65),(51,72),(37,71),(22,67),(9,61)])
    poly(d,'#396b7c',[(7,48),(13,36),(23,30),(38,32),(49,39),(62,33),(73,37),(78,46),(75,54),(65,62),(51,69),(38,67),(22,65),(10,60)])
    poly(d,'#5f8d8c',[(10,48),(16,38),(28,32),(37,34),(46,41),(53,42),(63,35),(72,38),(75,45),(71,51),(62,57),(52,59),(44,65),(30,63),(15,59)])
    poly(d,'#8fa99a',[(11,46),(18,37),(28,34),(38,36),(42,40),(34,44),(24,43),(21,48),(15,50)])
    poly(d,'#779d94',[(46,53),(53,45),(62,38),(70,39),(73,43),(67,49),(61,50),(54,55)])
    fio(d,'#adc2a4',[(14,45),(18,40),(24,37),(31,37),(35,39)],2)
    fio(d,'#79a8a2',[(25,62),(31,62),(35,64),(42,64),(46,61)])
    coral(d,28,47,1.0)
    coral(d,59,48,.82,False)
    for x,y in [(18,54),(24,56),(48,58),(67,48),(39,54),(53,63)]:
        fio(d,'#aac0a9',[(x,y),(x+2,y-1)])
        d.point((x+1,y),fill='#467c82')

def copa(d,x,y,k):
    def forma(c,pts): poly(d,c,[(x+round(a*k),y+round(b*k)) for a,b in pts])
    forma('#23584f',[(-17,5),(-16,-3),(-12,-8),(-6,-10),(-5,-14),(5,-15),(9,-11),(15,-9),(18,-3),(16,6),(11,10),(4,12),(-7,11),(-13,8)])
    forma('#398065',[(-15,3),(-13,-5),(-6,-8),(-3,-13),(5,-13),(10,-9),(15,-6),(16,-1),(13,6),(6,9),(-5,9),(-10,6)])
    forma('#5f9f65',[(-14,0),(-10,-6),(-5,-7),(-3,-11),(4,-12),(9,-8),(8,-5),(13,-2),(11,2),(6,4),(0,3),(-4,7),(-10,5)])
    forma('#90b86b',[(-11,-1),(-8,-6),(-4,-7),(-1,-10),(4,-10),(7,-8),(3,-7),(0,-4),(-6,-4),(-8,0)])
    forma('#aec679',[(-7,-6),(-2,-8),(1,-8),(0,-6),(-4,-5)])

def mangue(d):
    """Duas copas conectadas por raízes, mas sem obstruir o canal jogável."""
    poly(d,'#254950',[(9,39),(15,30),(25,27),(40,30),(52,28),(64,32),(72,40),(67,50),(56,56),(36,61),(17,58),(10,51)])
    poly(d,'#37675d',[(10,38),(19,32),(31,30),(42,34),(54,30),(65,34),(70,41),(65,48),(57,53),(37,58),(20,55),(12,48)])
    for x,y,dx,dy in [(28,29,-17,13),(28,30,-13,20),(29,31,6,21),(28,31,15,8),
                     (53,27,14,15),(52,29,11,16),(51,30,-7,23),(52,30,-14,10)]:
        ramo=[(x,y),(x+dx//3,y+dy//3),(x+dx*2//3,y+dy*2//3),(x+dx,y+dy)]
        fio(d,'#654c50',ramo,5)
        fio(d,'#b5855f',[(a-1,b-1) for a,b in ramo],2)
        fio(d,'#d7a474',[(a-1,b-2) for a,b in ramo[1:]],1)
    copa(d,25,24,1.0)
    copa(d,51,20,1.05)
    copa(d,39,31,.78)
    fio(d,'#5a9080',[(12,50),(20,53),(25,53),(29,56),(36,56)])
    fio(d,'#75a491',[(42,52),(47,52),(52,50),(58,50)])

ESPEC = {
    'praia': ((7,0),duna),
    'recifes': ((0,4),recife),
    'mangue': ((3,4),mangue),
}

def aplicar(im, tema, linhas, origem, tamanho):
    (x,y),desenhar=ESPEC[tema]
    assert all(linhas[j][i]=='~' for i in (x,x+1) for j in (y,y+1))
    art=Image.new('RGBA',(tamanho*2,tamanho*2))
    desenhar(ImageDraw.Draw(art))
    assert set(art.getchannel('A').getdata())=={0,255}
    im.paste(art,(origem[0]+tamanho*x,origem[1]+tamanho*y),art.getchannel('A'))

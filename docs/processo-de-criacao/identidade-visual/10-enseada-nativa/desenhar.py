def rocha(x,y,forma):
    if forma==0:
        a=[(-6,1),(-6,-2),(-3,-6),(1,-7),(5,-5),(7,-2),(5,2),(1,4)]
        b=[(-5,-2),(-3,-5),(1,-7),(4,-5),(3,-3),(-2,-2)]
    elif forma==1:
        a=[(-8,1),(-7,-3),(-4,-4),(-2,-7),(3,-7),(7,-4),(9,1),(6,4),(-5,4)]
        b=[(-7,-2),(-4,-3),(-2,-6),(3,-6),(5,-4),(3,0),(-3,1)]
    else:
        a=[(-5,0),(-5,-4),(-2,-6),(2,-8),(5,-4),(5,2),(1,4),(-3,3)]
        b=[(-4,-3),(-1,-5),(2,-7),(4,-4),(2,-1),(-2,0)]
    p(desloc([(-6,2),(3,0),(9,2),(6,5),(-4,5)],x,y),'#466e59')
    p(desloc(a,x,y),GNAISSE,ESCURA)
    p(desloc(b,x,y),PEDRA_LUZ)
    linha(desloc([(-3,-3),(0,-4),(2,-4)],x,y),'#d1b68f')
    linha(desloc([(1,2),(5,1)],x,y),'#6c7770')


def desenhar(camadas):
    quadro = Image.new("RGBA", (31, 23))
    pincel = ImageDraw.Draw(quadro)
    for cor, vertices in camadas:
        pincel.polygon(vertices, fill=PALETA[cor])
    assert set(quadro.getchannel("A").getdata()) == {0, 255}
    return quadro



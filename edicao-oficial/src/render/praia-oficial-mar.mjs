export function pintarEspumaDaAreia(pintar        , podePintar                                   ,
  mapa                   , quadro        , alta         , paleta = PALETA_PRAIA, fechados                      = new Set())       {
  mapa.forEach((fila, j) => [...fila].forEach((casa, i) => {
    if (casa === '#' || (alta && casa === '=') || fechados.has(`${i},${j}`) || (mapa[j + 1]?.[i] ?? '#') !== '#') return;
    const x = quadro.origemX + i * CASA_PRAIA;
    const y = quadro.origemY + j * CASA_PRAIA;
    const semente = 731 + 57 * i + 121 * j + 82 + 17 * mapa.length + 39 * fila.length;
    const [a, la, b, lb, o1, o2] = [...(PINCEIS[semente] ?? '9b2633')].map(n => Number.parseInt(n, 16));
    const faixas = (i + j + 2) % 4 === 3 ? [[b + 30, lb]] : [[a, la], [b + 30, lb]];
    faixas.forEach(([ini, l], indice) => {
      const branca = (j * 5 + i * 3 + indice + 2) % 3 !== 1;
      const on = (indice === 0 ? o1 : o2) + brilhoDaEspuma(x+ini,y);
      for (let k = 0; k < l; k++) {
        const recuo = 1 + Number(k % 11 === 0 || k % 11 === 10);
        const largura = 1 + Number(k % 5 === 2 || k % 5 === 3);
        for (let e = 0; e < largura; e++) {
          const px = x + ini + k, py = y + 47 + recuo + e;
          if (podePintar(px, py)) pintar(e === 0 && branca && on <= k && k < on + Number(l >= 10) + 2
            ? paleta.espuma[1] : paleta.espuma[0], px, py, 1, 1);
        }
      }
    });
  }));
}

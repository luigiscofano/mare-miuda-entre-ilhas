function separado([x, y, w, h]           , [u, v, p, q]           , margem        )          {
  return x + w + margem <= u || u + p + margem <= x || y + h + margem <= v || v + q + margem <= y;
}

export function pintarMarPraia(pintar        , mapa                   , quadro        ,
  estruturas                           )       {
  const { largura, altura, origemX, origemY } = quadro;
  pintar(MAR_PRAIA, 0, 0, largura, altura);
  const reservas              = estruturas.map(e => [e.x, e.y, e.largura, e.altura]);
  mapa.forEach((fila, j) => [...fila].forEach((casa, i) => {
    if (casa !== '#') reservas.push([origemX + i * CASA_PRAIA, origemY + j * CASA_PRAIA, CASA_PRAIA, CASA_PRAIA]);
  }));
  const reflexos=[];
  CANDIDATOS.forEach(([px, py], k) => {
    const x = Math.floor(px * largura / 100) - 8, y = Math.floor(py * altura / 100);
    const l = [16, 26, 21, 14, 19][k % 5];
    const espuma = [0, 4, 9, 15, 19, 23].includes(k);
    const caixa            = [x, y, l, espuma ? 7 : 4];
    if (reservas.some(r => !separado(caixa, r, 7))) return;
    reservas.push(caixa);
    if (!espuma) {
      reflexos.push([x,y,l,k % 3 ? 3 : 4]);
      return;
    }
    pintarCristaRetangular(pintar, { x, y, largura: l, pontaBranca: k % 2 === 1 }, ['#8bbeb1', '#eef0d9']);
  });
  for(const faixa of reduzirReflexos(reflexos))pintar('#205464',...faixa);
}

